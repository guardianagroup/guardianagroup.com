// Videollamada partida por defecto y botón para hacerla pequeña (dueño, 28 Oct 2026, 15:12)
const { chromium, devices } = require('playwright');
const S = '/tmp/pruebas-com/prueba-74/';
const espera = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch({ args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] }); const res = [];
  const ok = (n, c, x) => res.push((c ? 'OK   ' : 'FALLA') + ' ' + n + (x ? ' · ' + x : ''));
  const mk = async (disp) => { const c = await b.newContext(Object.assign({}, disp || { viewport: { width: 1280, height: 800 } }, { permissions: ['microphone', 'camera'], locale: 'es-ES' })); await c.addInitScript(() => { try { localStorage.setItem('guardiana-acceso', 'dueno'); } catch (e) {} }); const p = await c.newPage(); await p.goto('http://127.0.0.1:8802/orbita/comunicaciones/'); await p.waitForTimeout(1500); return p; };
  const vis = (p, s) => p.evaluate((s) => { const e = document.querySelector(s); return !!(e && !e.hidden && e.offsetParent !== null); }, s);
  const A = await mk(), B = await mk(devices['iPhone 13']);
  await A.click('#nueva'); await espera(1500);
  const codigo = (await A.textContent('#codigo')).replace(/\D/g, '');
  await B.tap('#unir'); await espera(300); await B.fill('#unir-codigo', codigo); await espera(300);
  if (await vis(B, '#unir-ok')) await B.tap('#unir-ok').catch(() => {});
  for (let i = 0; i < 40 && !(await vis(A, '#conv')); i++) await espera(500);
  await espera(2500);
  await A.mouse.move(600, 400); await A.mouse.move(610, 410); await A.click('#videollamar'); await espera(2500);
  await B.tap('#ll-contestar').catch(async () => { await B.evaluate(() => document.querySelector('#ll-contestar').click()); });
  for (let i = 0; i < 30 && !(await A.evaluate(() => !document.querySelector('#ll-tiempo').hidden)); i++) await espera(500);
  await espera(2500);
  const est = (p) => p.evaluate(() => { const c = document.querySelector('#ll-videos').closest('.gc-llamada') || document.querySelector('#llamada'); const bt = document.querySelector('#ll-tam'); return { div: !!(c && c.classList.contains('dividida')), lado: c ? [...c.classList].filter((x) => x.startsWith('lado-')).join(',') : '', boton: !!(bt && !bt.hidden && bt.offsetParent), et: bt ? bt.getAttribute('aria-label') : '' }; });
  const a1 = await est(A), b1 = await est(B);
  ok('ordenador: la videollamada empieza partida (tú a la derecha)', a1.div && /lado-der/.test(a1.lado), JSON.stringify(a1));
  ok('teléfono: empieza partida (tú abajo)', b1.div && /lado-abajo/.test(b1.lado), JSON.stringify(b1));
  ok('botón «Hacer pequeña tu imagen» a la vista', a1.boton && a1.et === 'Hacer pequeña tu imagen');
  await A.screenshot({ path: S + 'partida-1.png' }); await B.screenshot({ path: S + 'partida-movil.png' });
  await A.click('#ll-tam'); await espera(600);
  const a2 = await est(A);
  ok('al pulsarlo, tu imagen pasa a pequeña', !a2.div && a2.boton && a2.et === 'Pantalla dividida', JSON.stringify(a2));
  await A.screenshot({ path: S + 'partida-2.png' });
  await A.click('#ll-tam'); await espera(600);
  ok('y otra vez, partida', (await est(A)).div);
  await A.click('#ll-tam'); await espera(400);
  await A.click('#ll-colgar').catch(() => {}); await espera(2500);
  await A.mouse.move(600, 400); await A.mouse.move(612, 412); await A.click('#videollamar'); await espera(2500);
  await B.tap('#ll-contestar').catch(async () => { await B.evaluate(() => document.querySelector('#ll-contestar').click()); });
  for (let i = 0; i < 30 && !(await A.evaluate(() => !document.querySelector('#ll-tiempo').hidden)); i++) await espera(500);
  await espera(2500);
  ok('la siguiente videollamada vuelve a empezar partida', (await est(A)).div);
  console.log(res.join('\n')); await b.close();
})().catch((e) => { console.error('FALLO', e.message); process.exit(1); });
